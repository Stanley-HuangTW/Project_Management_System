import { existsSync, readFileSync } from "fs";
import path from "path";
import { describe, expect, it } from "vitest";
import {
  MANUAL_IMAGE_URL,
  manualImageNames,
  parseManual,
  renderManualHtml,
  searchManual,
  sectionIdFromText,
  toPlainText,
  visibleChapters,
} from "./manual";

const SAMPLE = `# 工作管理平台 使用手冊

> 適用版本:2026-10-28

## 目錄

1. [快速開始](#1-快速開始)
2. [管理者功能](#2-管理者功能)

**角色標示**:【全員】所有人

---

## 1. 快速開始

### 1.1 登入

![登入畫面](manual-images/01-login.jpg)

連續輸入錯誤 **5 次**會鎖定。

### 1.2 畫面總覽

| 編號 | 說明 |
|---|---|
| ① | 左側邊欄 |

---

## 2. 管理者功能

<!-- admin-only -->

### 2.1 使用者管理【管理者】

![使用者管理](manual-images/31-users.jpg)

新增使用者時填 Email。
`;

describe("parseManual", () => {
  const manual = parseManual(SAMPLE);

  it("reads the title, the intro and the legend (the TOC list is regenerated by the page)", () => {
    expect(manual.title).toBe("工作管理平台 使用手冊");
    expect(manual.legend).toBe("**角色標示**:【全員】所有人");
  });

  it("takes the version line out of the intro: date and notes separately", () => {
    const withNotes = parseManual("# 手冊\n\n> 適用版本:2026-10-28(含「A」、「B(C)」)\n>\n> 本文是示範資料\n\n## 1. 章\n");
    expect(withNotes.version).toBe("2026-10-28");
    expect(withNotes.versionNotes).toBe("含「A」、「B(C)」");
    expect(withNotes.intro).toBe("> 本文是示範資料");
    expect(manual.version).toBe("2026-10-28");
    expect(manual.versionNotes).toBeNull();
    expect(manual.intro).toBe("");
  });

  it("copes with a version line that has no notes, or none at all", () => {
    expect(parseManual("# 手冊\n\n> 適用版本:2026-01-02\n").versionNotes).toBeNull();
    expect(parseManual("# 手冊\n\n說明\n").version).toBeNull();
  });

  it("splits the chapters and numbers them", () => {
    expect(manual.chapters.map((c) => [c.id, c.number, c.title])).toEqual([
      ["ch-1", 1, "快速開始"],
      ["ch-2", 2, "管理者功能"],
    ]);
  });

  it("marks a chapter admin-only from the marker line and removes the marker", () => {
    expect(manual.chapters.map((c) => c.adminOnly)).toEqual([false, true]);
    expect(manual.chapters[1].markdown).not.toContain("admin-only");
  });

  it("drops the blank lines and the --- that separates a chapter from the next", () => {
    expect(manual.chapters[0].markdown.endsWith("| ① | 左側邊欄 |")).toBe(true);
  });

  it("lists the ### sections with stable anchors", () => {
    expect(manual.chapters[0].sections).toEqual([
      { id: "s-1-1", title: "1.1 登入" },
      { id: "s-1-2", title: "1.2 畫面總覽" },
    ]);
  });

  it("does not take a ### inside a code fence for a section", () => {
    const m = parseManual("## 1. 範例\n\n```\n### 不是標題\n```\n\n### 1.1 真的標題\n");
    expect(m.chapters[0].sections.map((s) => s.title)).toEqual(["1.1 真的標題"]);
  });

  it("understands CRLF files", () => {
    expect(parseManual(SAMPLE.replace(/\n/g, "\r\n")).chapters.map((c) => c.number)).toEqual([1, 2]);
  });
});

describe("visibleChapters", () => {
  const manual = parseManual(SAMPLE);

  it("hides the admin-only chapter from everyone but admins", () => {
    expect(visibleChapters(manual, false).map((c) => c.number)).toEqual([1]);
    expect(visibleChapters(manual, true).map((c) => c.number)).toEqual([1, 2]);
  });
});

describe("sectionIdFromText", () => {
  it("uses the number, including a trailing letter", () => {
    expect(sectionIdFromText("11.3b 風險、議題的待辦事項")).toBe("s-11-3b");
    expect(sectionIdFromText("21.4 資料庫備份與還原【管理者】")).toBe("s-21-4");
  });

  it("falls back to the text when there is no number", () => {
    expect(sectionIdFromText("常見問題 FAQ")).toBe("s-常見問題-faq");
  });

  it("ignores HTML tags", () => {
    expect(sectionIdFromText("<strong>3.2</strong> 欄位")).toBe("s-3-2");
  });
});

describe("renderManualHtml", () => {
  it("points images at the permission-checked image route and lazy-loads them", () => {
    const html = renderManualHtml("![登入畫面](manual-images/01-login.jpg)");
    expect(html).toContain(`src="${MANUAL_IMAGE_URL}01-login.jpg"`);
    expect(html).toContain('loading="lazy"');
    expect(html).toContain('alt="登入畫面"');
  });

  it("rewrites an inline <img> too", () => {
    const html = renderManualHtml('<table><tr><td><img src="manual-images/r1.jpg" width="210"></td></tr></table>');
    expect(html).toContain(`src="${MANUAL_IMAGE_URL}r1.jpg"`);
    expect(html).not.toContain('src="manual-images/');
  });

  it("opens external links in a new tab and leaves internal ones alone", () => {
    expect(renderManualHtml("[Mantis](https://mantisbt.org/)")).toContain('target="_blank" rel="noopener noreferrer"');
    expect(renderManualHtml("[上面](#ch-1)")).not.toContain("target=");
  });

  it("gives ### headings their anchor", () => {
    expect(renderManualHtml("### 1.1 登入")).toContain('<h3 id="s-1-1">1.1 登入</h3>');
  });

  it("renders tables and bold text", () => {
    const html = renderManualHtml("| a | b |\n|---|---|\n| **x** | y |");
    expect(html).toContain("<table>");
    expect(html).toContain("<strong>x</strong>");
  });

  it("keeps the two-space line break", () => {
    expect(renderManualHtml("第一行  \n第二行")).toContain("<br>");
  });
});

describe("manualImageNames", () => {
  it("lists each image file once", () => {
    expect(manualImageNames("![a](manual-images/a.jpg)\n![b](manual-images/b.png) ![again](manual-images/a.jpg)")).toEqual(["a.jpg", "b.png"]);
  });

  it("also counts an inline <img> (the side-by-side sidebar screenshots)", () => {
    expect(manualImageNames('<td><img src="manual-images/r1.jpg" width="210"></td>')).toEqual(["r1.jpg"]);
  });

  it("ignores images from elsewhere", () => {
    expect(manualImageNames("![x](https://example.com/x.png)")).toEqual([]);
  });
});

describe("toPlainText", () => {
  it("drops images, link targets and table / emphasis symbols", () => {
    const text = toPlainText("![圖](manual-images/a.jpg)\n\n| 編號 | 說明 |\n|---|---|\n| ① | **側邊欄** 與 [連結](https://x.y) |");
    expect(text).toBe("編號 說明 ① 側邊欄 與 連結");
  });
});

describe("searchManual", () => {
  const manual = parseManual(SAMPLE);

  it("finds the chapters that contain the text, with a count and context", () => {
    const hits = searchManual(manual.chapters, "Email");
    expect(hits).toHaveLength(1);
    expect(hits[0]).toMatchObject({ chapterId: "ch-2", number: 2, count: 1 });
    expect(hits[0].snippets[0].match).toBe("Email");
    expect(hits[0].snippets[0].before.endsWith("新增使用者時填 ")).toBe(true);
  });

  it("is case-insensitive", () => {
    expect(searchManual(manual.chapters, "email")).toHaveLength(1);
  });

  it("matches the chapter title too", () => {
    expect(searchManual(manual.chapters, "快速開始").map((h) => h.chapterId)).toEqual(["ch-1"]);
  });

  it("needs at least two characters", () => {
    expect(searchManual(manual.chapters, "登")).toEqual([]);
    expect(searchManual(manual.chapters, " ")).toEqual([]);
  });

  it("only looks in the chapters it is given (so admin chapters stay out of a member's results)", () => {
    expect(searchManual(visibleChapters(manual, false), "Email")).toEqual([]);
  });

  it("keeps only the first few snippets but counts every hit", () => {
    const chapter = parseManual("## 1. 重複\n\n" + "待辦 ".repeat(10)).chapters;
    const [hit] = searchManual(chapter, "待辦");
    expect(hit.count).toBe(10);
    expect(hit.snippets).toHaveLength(3);
  });
});

describe("the real manual (docs/使用手冊.md)", () => {
  const docs = path.join(process.cwd(), "docs");
  const manual = parseManual(readFileSync(path.join(docs, "使用手冊.md"), "utf8"));

  it("has all its chapters, numbered in order", () => {
    expect(manual.chapters.length).toBeGreaterThanOrEqual(23);
    expect(manual.chapters.map((c) => c.number)).toEqual(manual.chapters.map((_, i) => i + 1));
  });

  it("keeps the 管理者功能 chapter (and only that one) admin-only", () => {
    expect(manual.chapters.filter((c) => c.adminOnly).map((c) => c.title)).toEqual(["管理者功能"]);
  });

  it("is searchable and a member's results never include the admin chapter", () => {
    const all = searchManual(manual.chapters, "稽核軌跡");
    expect(all.some((h) => h.title === "管理者功能")).toBe(true);
    expect(searchManual(visibleChapters(manual, false), "稽核軌跡").some((h) => h.title === "管理者功能")).toBe(false);
  });

  it("only references images that exist", () => {
    const missing = manual.chapters
      .flatMap((c) => manualImageNames(c.markdown))
      .filter((name) => !existsSync(path.join(docs, "manual-images", name)));
    expect(missing).toEqual([]);
  });

  it("renders every chapter without leaving the marker or raw image paths behind", () => {
    for (const chapter of manual.chapters) {
      const html = renderManualHtml(chapter.markdown);
      expect(html).not.toContain("admin-only");
      expect(html).not.toContain('src="manual-images/');
    }
  });

  it("gives every ### section a distinct anchor inside its chapter", () => {
    for (const chapter of manual.chapters) {
      const ids = chapter.sections.map((s) => s.id);
      expect(new Set(ids).size).toBe(ids.length);
    }
  });
});
